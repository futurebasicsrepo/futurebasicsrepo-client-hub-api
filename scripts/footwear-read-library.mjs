// Each library shoe's own build, read off its drawing and its name (no AI), so a shoe started from it is drafted as that shoe and not only as
// its kind: the collar height and the toe spring traced from its outside drawing (the same outline reading the Pattern page's "read the
// picture" makes), the upper from its name (suede, mesh, leather, canvas…), a toe cap where it has one (a T-toe, a cap toe).
//
//   node scripts/footwear-read-library.mjs     → src/lab-footwear-template-specs.js
import { readFileSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';
import { FOOTWEAR_TEMPLATES } from '../src/lab-footwear-templates.js';
import { silhouette, sideView, proposal } from '../src/lab-shoe-read.js';
import { shoeSvg } from '../src/lab-shoe-draw.js';
import { fwDefaults, FW_STYLES, UPPERS } from '../src/lab-footwear.js';
const out = {};
for (const t of FOOTWEAR_TEMPLATES) {
  const j = JSON.parse(readFileSync(new URL(`../src/footwear-templates/${t.id}.json`, import.meta.url), 'utf8')), style = FW_STYLES[t.style] ? t.style : null; if (!style || !j.views?.lateral) continue;
  const png = await sharp(Buffer.from(shoeSvg(j.views.lateral, { width: 1024 }))).flatten({ background: '#ffffff' }).png().toBuffer(), sil = await silhouette(png);
  const e = {};
  if (sideView(sil)) for (const c of proposal(fwDefaults(style), sil, null).changes || []) if (['collar', 'spring', 'heel'].includes(c.key)) e[c.key] = c.to;
  const n = `${t.id} ${t.label}`.toLowerCase(), up = ['suede', 'nubuck', 'canvas', 'mesh', 'knit', 'leather'].find(u => UPPERS[u] && new RegExp(u).test(n));
  if (up) e.upper = up; if (/t-toe|cap toe|toe cap/.test(n)) e.toeCap = true;
  out[t.id] = e; console.log(t.id.padEnd(38), JSON.stringify(e));
}
writeFileSync(new URL('../src/lab-footwear-template-specs.js', import.meta.url), `// Generated by scripts/footwear-read-library.mjs: each library shoe's own build (collar height and toe spring in inches traced from its
// outside drawing; its upper and toe cap from its name). A shoe started from the library is drafted with it. Do not edit by hand.
export const FOOTWEAR_TEMPLATE_SPECS = ${JSON.stringify(out, null, 1)};
`);
