// Builds the Design Lab's library of footwear flats: original footwear technical flats (outside, inside, top, bottom and heel), drawn once by
// the image model in a neutral prototype colourway (light-grey upper, darker-grey overlays, pale-cream midsole, mid-grey outsole) and traced
// into panels by src/lab-shoe-draw.js. The styles and their types come from scripts/footwear-templates/catalogue.mjs; a style is built once
// its drawings exist. A designer starts a footwear concept from one in the Sketch library and recolours and reshapes it in the Studio; its
// pattern is drafted by src/lab-footwear.js in the catalogue's pattern style (no image model needed then).
// Writes src/footwear-templates/<id>.json (each view's drawing), src/footwear-templates/thumbs/<id>.webp and src/lab-footwear-templates.js.
//   node scripts/footwear-templates/build.mjs <folder with <name>-lateral.png, <name>-medial.png, <name>-top.png, <name>-bottom.png, <name>-back.png>
//   (<name> is the id without its "footwear-" prefix)
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { traceShoe, shoeSvg, SHOE_VIEW_IDS } from '../../src/lab-shoe-draw.js';
import { LIBRARY, TYPES, CONSTRUCTIONS } from './catalogue.mjs';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..'), sharp = createRequire(join(ROOT, 'package.json'))('sharp');
const SRC = process.argv[2]; if (!SRC) { console.error('usage: build.mjs <folder>'); process.exit(1); }
const OUT = join(ROOT, 'src', 'footwear-templates'); mkdirSync(join(OUT, 'thumbs'), { recursive: true });
const r2 = v => Math.round(v * 100) / 100, list = [];
for (const e of LIBRARY) {
  const name = e.id.replace(/^footwear-/, ''), views = {};
  for (const v of SHOE_VIEW_IDS) {
    const f = join(SRC, `${name}-${v}.png`); if (!existsSync(f)) continue;
    const { svg, ...dw } = await traceShoe(readFileSync(f));
    // a library drawing keeps only what the page needs, and its numbers to two places
    views[v] = { ...dw, panels: dw.panels.map(p => ({ ...p, box: Object.fromEntries(Object.entries(p.box).map(([k, x]) => [k, r2(x)])) })), source: `library:${e.id}` };
  }
  if (!views.lateral) continue; // not drawn yet
  // the pattern style a drafted shoe opens in; a style the pattern does not draft yet opens on its nearest (the drawing is what shows)
  const style = e.pattern.startsWith('new:') ? null : e.pattern, variant = style && e.variant ? e.variant : undefined;
  writeFileSync(join(OUT, `${e.id}.json`), JSON.stringify({ id: e.id, type: e.type, label: e.label, style, ...(variant ? { variant } : {}), views }));
  await sharp(Buffer.from(shoeSvg(views.lateral, { width: 480 }))).resize(300, 240, { fit: 'contain', background: '#ffffff' }).flatten({ background: '#ffffff' }).webp({ quality: 80 }).toFile(join(OUT, 'thumbs', `${e.id}.webp`));
  list.push({ id: e.id, type: e.type, group: TYPES[e.type], label: e.label, style, ...(variant ? { variant } : {}), construction: e.construction, built: CONSTRUCTIONS[e.construction].split(':')[0], closure: e.closure, height: e.height, range: 'footwear', views: Object.keys(views) });
  console.log(e.id, Object.entries(views).map(([k, d]) => `${k}:${d.panels.length}`).join(' '));
}
writeFileSync(join(ROOT, 'src', 'lab-footwear-templates.js'), `// Generated by scripts/footwear-templates/build.mjs: the library of footwear flats (original drawings, traced into panels; each view's drawing
// is in src/footwear-templates/<id>.json), grouped by type. Do not edit by hand: change the script and run it again.
export const FOOTWEAR_TEMPLATES = ${JSON.stringify(list, null, 0).replace(/\},\{/g, '},\n{')};
`);
console.log(`${list.length} footwear flats`);
