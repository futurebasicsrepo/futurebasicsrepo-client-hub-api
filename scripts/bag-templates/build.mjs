// Builds the Design Lab's library of bag flats: original bag technical flats (front, back, side), drawn once by the image model in a neutral
// prototype colourway (light-grey body, darker-grey webbing and trim, black hardware) and traced into panels by src/lab-shoe-draw.js.
// A designer starts a bag concept from one in the Sketch library and recolours and reshapes it in the Studio (no image model needed then).
// Writes src/bag-templates/<id>.json (each view's drawing), src/bag-templates/thumbs/<id>.webp and src/lab-bag-templates.js (the list).
//   node scripts/bag-templates/build.mjs <folder with <id>-front.png, <id>-back.png, <id>-side.png>
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { traceShoe, shoeSvg } from '../../src/lab-shoe-draw.js';
import { BAG_TYPES } from '../../src/lab-bags.js';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..'), sharp = createRequire(join(ROOT, 'package.json'))('sharp');
const SRC = process.argv[2]; if (!SRC) { console.error('usage: build.mjs <folder>'); process.exit(1); }
const OUT = join(ROOT, 'src', 'bag-templates'); mkdirSync(join(OUT, 'thumbs'), { recursive: true });
// the library: one per kind of bag, each named for what it is
const LIBRARY = [['rolltop', 'Rolltop backpack'], ['backpack', 'Clamshell zip backpack'], ['drawstring', 'Top-loader backpack'], ['sling', 'Crescent sling'], ['tote', 'Structured tote'], ['helmet', 'Helmet bag'],
  ['briefcase', 'Two-way work bag'], ['messenger', 'Flap messenger'], ['duffel', 'Barrel duffel'], ['waist', 'Waist bag'], ['pouch', 'Crossbody pouch']];
const r2 = v => Math.round(v * 100) / 100, list = [];
for (const [type, label] of LIBRARY) {
  const views = {};
  for (const v of ['front', 'back', 'side']) {
    const f = join(SRC, `${type}-${v}.png`); if (!existsSync(f)) continue;
    const { svg, ...dw } = await traceShoe(readFileSync(f));
    // a library drawing keeps only what the page needs, and its numbers to two places
    views[v] = { ...dw, panels: dw.panels.map(p => ({ ...p, box: Object.fromEntries(Object.entries(p.box).map(([k, x]) => [k, r2(x)])) })), source: `library:bag-${type}` };
  }
  if (!views.front) { console.warn('skipped', type, '(no front)'); continue; }
  const id = `bag-${type}`; writeFileSync(join(OUT, `${id}.json`), JSON.stringify({ id, type, label, views }));
  await sharp(Buffer.from(shoeSvg(views.front, { width: 480 }))).resize(240, 300, { fit: 'contain', background: '#ffffff' }).flatten({ background: '#ffffff' }).webp({ quality: 80 }).toFile(join(OUT, 'thumbs', `${id}.webp`));
  const t = BAG_TYPES[type]; list.push({ id, type, label, style: 'bag', range: 'bags', views: Object.keys(views), size: t ? `${t.w} × ${t.h} × ${t.d} in, ${t.l} L` : '' });
  console.log(id, Object.entries(views).map(([k, d]) => `${k}:${d.panels.length}`).join(' '));
}
writeFileSync(join(ROOT, 'src', 'lab-bag-templates.js'), `// Generated by scripts/bag-templates/build.mjs: the library of bag flats (original drawings, traced into panels; each view's drawing is in
// src/bag-templates/<id>.json). Do not edit by hand: change the script and run it again.
export const BAG_TEMPLATES = ${JSON.stringify(list, null, 0).replace(/\},\{/g, '},\n{')};
`);
